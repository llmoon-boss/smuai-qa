# ---------- SQLite 适配层（模拟 pymysql 的用法） ----------
class _SqliteCursor:
    """把 %s 占位符与字典行包装成 pymysql 的用法。"""

    def __init__(self, cur):
        self._cur = cur

    def execute(self, sql, params=()):
        self._cur.execute(sql.replace("%s", "?"), tuple(params))
        return self

    def executemany(self, sql, seq):
        self._cur.executemany(sql.replace("%s", "?"), [tuple(x) for x in seq])
        return self

    def fetchone(self):
        row = self._cur.fetchone()
        return dict(row) if row is not None else None

    def fetchall(self):
        return [dict(r) for r in self._cur.fetchall()]

    @property
    def rowcount(self):
        return self._cur.rowcount

    def close(self):
        self._cur.close()

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()
        return False


class _SqliteConn:
    def __init__(self, conn):
        self._conn = conn

    def cursor(self):
        return _SqliteCursor(self._conn.cursor())

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()


def _sqlite_ddl():
    """把 schema.sql（MySQL 方言）转成 SQLite 可执行的建表语句。"""
    with open(SCHEMA_PATH, encoding="utf-8") as f:
        raw = f.read()
    stmts = []
    for chunk in raw.split(";"):
        lines = [ln for ln in chunk.splitlines() if not ln.strip().startswith("--")]
        s = "\n".join(lines).strip()
        if not s:
            continue
        s = re.sub(r"COMMENT\s+'[^']*'", "", s)          # 字段注释
        s = s.replace("INT AUTO_INCREMENT PRIMARY KEY",
                      "INTEGER PRIMARY KEY AUTOINCREMENT")
        s = re.sub(r"\)\s*ENGINE\s*=.*$", ")", s, flags=re.S | re.I)  # 引擎/字符集
        stmts.append(s.strip())
    return stmts


def get_conn():
    # 获取数据库连接
    if DB_ENGINE == "sqlite":
        db_dir = os.path.dirname(DB_PATH)
        if db_dir:
            os.makedirs(db_dir, exist_ok=True)
        conn = sqlite3.connect(DB_PATH, timeout=15)
        conn.row_factory = sqlite3.Row
        try:
            conn.execute("PRAGMA journal_mode=WAL")
        except sqlite3.Error:
            pass
        return _SqliteConn(conn)

    import pymysql  # 只有用 MySQL 时才需要
    # DictCursor：查询结果以字典列表返回，便于 jsonify
    return pymysql.connect(**DB_CONFIG, cursorclass=pymysql.cursors.DictCursor)


@contextmanager
def db_conn():
    #连接上下文管理器：自动提交、异常回滚、关闭连接
    conn = get_conn()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db():
    #执行建表，并写入种子问答对与默认管理员
    if DB_ENGINE == "sqlite":
        statements = _sqlite_ddl()
    else:
        with open(SCHEMA_PATH, encoding="utf-8") as f:
            statements = [s for s in f.read().split(";") if s.strip()]
    with db_conn() as conn:
        with conn.cursor() as cur:
            for stmt in statements:
                cur.execute(stmt)
    _seed()


